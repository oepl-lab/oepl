-- 교수 프로필 (행은 항상 1개, id = 'default')
-- members.sql과 마찬가지로 admins.sql(public.is_admin()) 이후에 실행할 것.
create table if not exists public.professor (
  id text primary key default 'default' check (id = 'default'),
  name_ko text not null,
  name_en text not null,
  affiliation_kr text not null default '',
  affiliation_en text not null default '',
  email text not null default '',
  scholar text not null default '',
  photo_url text,
  updated_at timestamptz not null default now()
);

-- 교수 이력: 한 줄 = 한 행, sort_order 순서로 표시
create table if not exists public.professor_career (
  id bigint generated by default as identity primary key,
  professor_id text not null default 'default'
    references public.professor (id) on delete cascade,
  period text not null,
  text_kr text not null,
  text_en text not null,
  sort_order int not null default 0
);

create index if not exists professor_career_order_idx
  on public.professor_career (professor_id, sort_order);

alter table public.professor enable row level security;
alter table public.professor_career enable row level security;

drop policy if exists "professor_public_read" on public.professor;
create policy "professor_public_read" on public.professor for select using (true);
drop policy if exists "professor_admin_write" on public.professor;
create policy "professor_admin_write" on public.professor for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "professor_career_public_read" on public.professor_career;
create policy "professor_career_public_read" on public.professor_career for select using (true);
drop policy if exists "professor_career_admin_write" on public.professor_career;
create policy "professor_career_admin_write" on public.professor_career for all to authenticated using (public.is_admin()) with check (public.is_admin());

-- 프로필 저장 + 이력 전체 교체를 한 트랜잭션으로 처리한다.
-- 이력만 지워지고 새 이력이 들어가지 않은 상태가 남지 않게 하기 위함이다.
-- security invoker이므로 위 RLS 정책도 그대로 적용된다 (is_admin 검사와 이중 확인).
--
-- p 형식:
--   { "name_ko", "name_en", "affiliation_kr", "affiliation_en", "email", "scholar",
--     "photo_url", "career": [{ "period", "text_kr", "text_en" }, ...] }
create or replace function public.save_professor(p jsonb)
returns void
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
begin
  if not public.is_admin() then
    raise exception 'not authorized' using errcode = '42501';
  end if;

  insert into public.professor (
    id, name_ko, name_en, affiliation_kr, affiliation_en, email, scholar, photo_url, updated_at
  )
  values (
    'default',
    coalesce(p->>'name_ko', ''),
    coalesce(p->>'name_en', ''),
    coalesce(p->>'affiliation_kr', ''),
    coalesce(p->>'affiliation_en', ''),
    coalesce(p->>'email', ''),
    coalesce(p->>'scholar', ''),
    nullif(p->>'photo_url', ''),
    now()
  )
  on conflict (id) do update set
    name_ko = excluded.name_ko,
    name_en = excluded.name_en,
    affiliation_kr = excluded.affiliation_kr,
    affiliation_en = excluded.affiliation_en,
    email = excluded.email,
    scholar = excluded.scholar,
    photo_url = excluded.photo_url,
    updated_at = now();

  delete from public.professor_career where professor_id = 'default';

  insert into public.professor_career (professor_id, period, text_kr, text_en, sort_order)
  select
    'default',
    coalesce(e->>'period', ''),
    coalesce(e->>'text_kr', ''),
    coalesce(e->>'text_en', ''),
    (ord - 1)::int
  from jsonb_array_elements(coalesce(p->'career', '[]'::jsonb)) with ordinality as t(e, ord);
end;
$$;

revoke all on function public.save_professor(jsonb) from public, anon;
grant execute on function public.save_professor(jsonb) to authenticated;
